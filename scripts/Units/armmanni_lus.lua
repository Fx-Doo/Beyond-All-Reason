function UpdateTargetHeading()
	while(true)do -- we want to run this thread and update target heading frequently
		local pos = GetTargetPos()
			-- Spring.Echo(pos)
		if pos then
			local ux, uy, uz = Spring.GetUnitPosition(unitID)
			local dirx, diry, dirz =  pos[1] - ux, pos[2] - uy, pos[3] - uz
			curHeading = 2*math.pi*((Spring.GetUnitHeading(unitID) + 32768) / 65536)
			local wtdHeading = 2*math.pi*((Spring.GetHeadingFromVector(dirx, dirz) + 32768) / 65536)
			stHeading = wtdHeading
		else
			stHeading = nil
		end
		Sleep(100)
	end
end

function Moving() -- we want to run this thread and update move goals heading frequently; somehow it was initially meant 
-- to run only between a startmoving and a stopmoving call, so it didnt have nil checks on move goals.
-- But somehow it doesnt error out even when there is no active command. Cheers.
	while true do
		local data = Spring.GetUnitMoveTypeData(unitID)
		local fgx, fgy, fgz = fakeMoveGoal.x, fakeMoveGoal.y, fakeMoveGoal.z
		local mgoal = {}
		if fgx and fgz and data.goalx == fgx and data.goalz == fgz then
			mgoal = lastmGoal
		else
			mgoal = {data.goalx, data.goaly, data.goalz}
		end
		local ux, uy, uz = Spring.GetUnitPosition(unitID)
		local dirx, diry, dirz = mgoal[1] - ux, mgoal[2] - uy, mgoal[3] - uz
		curHeading = 2*math.pi*((Spring.GetUnitHeading(unitID) + 32768) / 65536)
		local wtdHeading = 2*math.pi*((Spring.GetHeadingFromVector(dirx, dirz) + 32768) / 65536)
		mHeading = wtdHeading
		Decide()
		lastmGoal = mgoal
		Sleep(100)
	end
end

function Decide() -- this is where we decide what kind of movement we should perform
-- It is important to note that this does no "prediction" at all.
	if stHeading then -- If we have a target
		if mHeading then -- if we have a move heading//goal position
			local delta = (mHeading - stHeading)% (2*math.pi)
			if delta > (math.pi/2) and  delta < (3/2 * math.pi) then -- if the goal position is on the opposite side to the target position
				StartReversing()
			else
				StopReversing()
			end
		else
			StopReversing()
		end
	else
		StopReversing()
	end
end

