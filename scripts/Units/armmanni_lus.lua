function GetTargetPos()
	local ttype = notarget
	local tx, ty, tz

	if not tx then
		local targetList = GG.getUnitTargetList(unitID) -- Get target from target list, this is either the first target in queue, but inactive, or the current index if one is active
		if targetList then
			local ID = GG.getUnitTargetIndex(unitID) or 1
			local maybeID = GG.getUnitTargetList(unitID)[ID].target
			if type(maybeID) == "table" then
				tx, ty, tz = maybeID[1], maybeID[2], maybeID[3]
			else
				tx, ty, tz = Spring.GetUnitPosition(maybeID)
			end
			ttype = settarget

		end
	end	if not tx then
		local _,_,maybeID = Spring.GetUnitWeaponTarget(unitID, 1) -- Fall back to getting autogenerated target (or attack commands targets)
		-- note: do we actually want a unit to decide to reverse just because a tick came by ? maybe disable this and just use set target?
		if maybeID then
			if type(maybeID) == "table" then
				tx, ty, tz = maybeID[1], maybeID[2], maybeID[3]
			else
				tx, ty, tz = Spring.GetUnitPosition(maybeID)
			end
			ttype = autotarget
		end
	end
	if tx then
		local ux,uy,uz = Spring.GetUnitPosition(unitID) -- ignore target beyond 1.5* range for set target and 1*range for autotargets
		local dist = math.sqrt((tx-ux)^2 + (tz-uz)^2)
		local range = Spring.GetUnitMaxRange(unitID)
		if (ttype == settarget and dist > 1.5*range) or (ttype == autotarget and dist > range) then
			-- Spring.Echo("target was cancelled")
			tx = nil
			ttype = notarget
		end
	end
	return tx and {tx,ty,tz} or nil -- return nil if no target was found
end

