local function Normalize(dtx, dty, dtz)
    local len = math.sqrt(dtx*dtx + dty*dty + dtz*dtz)
    if len == 0 then
        return 0, 0, 0
    end
    return dtx / len, dty / len, dtz / len
end

function StopReversing() -- as simple as that; just set maxReverseSpeed to 0. Eventually if it happens that it turns the wrong way when going back to frontward movement, we can do a similar manual turn to the reversing one
	if reversing then
		Spring.MoveCtrl.SetGroundMoveTypeData(unitID, "maxReverseSpeed", 0)
		reversing = false
	end
end



function CheckIfINeedToTurnAroundManually() -- this thread is called when starting to reverse because we want to make sure we don't actually need to turn the vehicle around
	while (reversing) do
		local delta  = (curHeading-mHeading)%(2*math.pi) -- the issue is that by issuing a movegoal pos in this, the next Moving() thread call will update mheading.
		-- I could prevent that by blocking moving() when this thread is running a turn process, but i'm afraid that would result in delays if the turn has to be cancelled mid/way.
		-- "fixed" by registering the given fake movegoal and comparing it to the mGoal=> if it's == then use last known goal for mheading calculations
		if delta <= math.pi/2 or delta >= 3*math.pi/2 then
			Spring.MoveCtrl.SetGroundMoveTypeData(unitID, "maxReverseSpeed", 0) -- we need to force it to go forward until it can go backwards... soo painful
			local ux,uy,uz = Spring.GetUnitPosition(unitID)
			local pos = GetTargetPos() -- since we're reusing some of the previously acquired data in the target thread, this can be optimized++
			
			if pos then
				tx = pos[1] or ux
				ty = pos[2] or uy
				tz = pos[3] or uz
				dtx, dty, dtz = tx - ux, ty - uy, tz - uz
				dtx,dty,dtz = Normalize(dtx, dty, dtz) --  normalized direction to target
				local vx,vy,vz,v = Spring.GetUnitVelocity(unitID) -- linear speed
				local brakeRate = UnitDefs[unitDefID].maxDec * 30
				local v = v*30 -- in elmos/seconds
				local ratio = v ~= 0 and ((v-brakeRate)/v) or 0
				fakeMoveGoal = {x=ux + dtx*16,y=uy-dty*16 ,z=uz+dtz*16} -- always towards target
				if v > 0 and v <= UnitDefs[unitDefID].speed * 0.3 then -- a slow happens naturally because we give very close move goals; once it reaches the threshold
					Spring.SetUnitVelocity(unitID, 0,0,0) -- force a stop so it can resume in opposite direction == move in reverse
				else
					Spring.SetUnitVelocity(unitID, vx*ratio, vy * ratio, vz * ratio) -- brake at brakeRate in case the natural slow isn't enough
				end
				Spring.SetUnitMoveGoal(unitID, fakeMoveGoal.x, fakeMoveGoal.y, fakeMoveGoal.z, 8, 0, true) -- give the move goal
			end
		else
			Spring.MoveCtrl.SetGroundMoveTypeData(unitID, "maxReverseSpeed", UnitDefs[unitDefID].speed) -- don't forget to restore once we're done
		end
		Sleep(1)
	end
end

function StartReversing() -- not as simple as a stop reversing, since here we need to force the unit to turn (and in the right direction)
	if not reversing then 
		Spring.MoveCtrl.SetGroundMoveTypeData(unitID, "maxReverseSpeed", UnitDefs[unitDefID].speed)
		reversing = true
		StartThread(CheckIfINeedToTurnAroundManually)
	end
end

